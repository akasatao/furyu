function toHiragana(text: string): string {
  return text.replace(/[\u30a1-\u30f6]/g, (ch) =>
    String.fromCharCode(ch.charCodeAt(0) - 0x60),
  );
}

export function toReading(text: string): string {
  const src = toHiragana(text);
  const keys = Object.keys(READING_DICT).sort((a, b) => b.length - a.length);
  let i = 0;
  let out = "";
  const chars = [...src];

  while (i < chars.length) {
    let matched = false;
    for (const key of keys) {
      const keyHira = toHiragana(key);
      const keyLen = [...key].length;
      const slice = chars.slice(i, i + keyLen).join("");
      if (slice === key || slice === keyHira) {
        out += READING_DICT[key];
        i += keyLen;
        matched = true;
        break;
      }
    }
    if (matched) continue;

    const ch = chars[i] ?? "";
    if (/[ぁ-んー]/.test(ch)) {
      out += ch;
      i += 1;
    } else if (/[\u4e00-\u9fff]/.test(ch)) {
      // 未登録は検出用に目立つ読み
      out += "？";
      i += 1;
    } else {
      i += 1;
    }
  }
  return out;
}

export function moraCountFromKana(kana: string): number {
  let count = 0;
  for (const ch of kana) {
    if (ch === "？" || /[ぁぃぅぇぉゃゅょゎ]/.test(ch)) {
      if (ch === "？") count += 1;
      continue;
    }
    if (/[ぁ-んー]/.test(ch)) count += 1;
  }
  return count;
}

export function moraCount(text: string): number {
  return moraCountFromKana(toReading(text));
}
